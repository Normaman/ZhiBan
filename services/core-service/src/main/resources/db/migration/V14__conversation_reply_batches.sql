CREATE TABLE reply_questions (
 message_id VARCHAR(100) PRIMARY KEY REFERENCES messages(id),
 conversation_id VARCHAR(100) NOT NULL REFERENCES conversations(id),
 sequence BIGINT GENERATED BY DEFAULT AS IDENTITY,
 answered_by VARCHAR(100) REFERENCES send_commands(id),
 answered_at BIGINT
);
CREATE INDEX reply_questions_pending ON reply_questions(conversation_id,answered_at,sequence);
CREATE TABLE reply_run_messages (
 run_id VARCHAR(100) NOT NULL REFERENCES agent_runs(id),
 message_id VARCHAR(100) NOT NULL REFERENCES reply_questions(message_id),
 PRIMARY KEY(run_id,message_id)
);
CREATE TABLE reply_command_messages (
 command_id VARCHAR(100) NOT NULL REFERENCES send_commands(id),
 message_id VARCHAR(100) NOT NULL REFERENCES reply_questions(message_id),
 PRIMARY KEY(command_id,message_id)
);
INSERT INTO reply_questions(message_id,conversation_id)
 SELECT id,conversation_id FROM messages
 WHERE direction='inbound' AND message_type<>'system_hint' AND platform_message_id IS NOT NULL
 AND state<>'sent' ORDER BY created_at,id;
INSERT INTO reply_run_messages(run_id,message_id)
 SELECT r.id,r.message_id FROM agent_runs r JOIN reply_questions q ON q.message_id=r.message_id;
INSERT INTO reply_command_messages(command_id,message_id)
 SELECT s.id,d.message_id FROM send_commands s JOIN drafts d ON d.id=s.draft_id
 JOIN reply_questions q ON q.message_id=d.message_id;
